/// The 12 palettes shipped by the Android app.
///
/// [storageKey] matches the app's enum names so persisted values stay
/// interchangeable.
enum PaletteId {
  violet('VIOLET'),
  emerald('EMERALD'),
  green('GREEN'),
  roseGold('ROSE_GOLD'),
  diSerria('DI_SERRIA'),
  rose('ROSE'),
  pearl('PEARL'),
  deepPlum('DEEP_PLUM'),
  pink('PINK'),
  purple('PURPLE'),
  aurora('AURORA'),
  dusk('DUSK');

  const PaletteId(this.storageKey);

  final String storageKey;

  static const PaletteId fallback = PaletteId.violet;

  static PaletteId fromStorageKey(String? key) =>
      values.firstWhere((p) => p.storageKey == key, orElse: () => fallback);

  AppPalette resolve(Brightness brightness) =>
      brightness == Brightness.dark ? _dark[this]! : _light[this]!;
}

